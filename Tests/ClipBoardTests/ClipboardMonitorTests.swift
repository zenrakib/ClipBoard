    // MARK: - Test 4: Deduplication & Stack Ordering

    @MainActor
    static func testDeduplicationAndStackOrdering() {
        let pb = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 50, autoStart: false)

        // Push Alpha, Beta, Gamma
        pb.clearContents()
        pb.setString("Alpha", forType: .string)
        monitor.checkPasteboard()

        pb.clearContents()
        pb.setString("Beta", forType: .string)
        monitor.checkPasteboard()

        pb.clearContents()
        pb.setString("Gamma", forType: .string)
        monitor.checkPasteboard()

        assert(monitor.items.map(\.text) == ["Gamma", "Beta", "Alpha"], "Stack order should be LIFO (newest at index 0)")

        // Re-copy "Beta" -> should be bumped to top, deduplicating the old position
        pb.clearContents()
        pb.setString("Beta", forType: .string)
        monitor.checkPasteboard()

        assert(monitor.items.map(\.text) == ["Beta", "Gamma", "Alpha"], "Beta should be promoted to index 0 without duplicates")
        assert(monitor.items.count == 3, "Stack count should remain 3 after deduplication")

        print("✓ Test 4 Passed: Deduplication and recency promotion")
    }

    // MARK: - Test 5: Max Capacity Limit (50 Items)

