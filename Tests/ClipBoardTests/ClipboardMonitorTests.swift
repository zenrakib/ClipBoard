    // MARK: - Test 1: Zero CPU Overhead & ChangeCount Guard

    @MainActor
    static func testZeroCpuOverhead() {
        let pb = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 50, autoStart: false)

        pb.clearContents()
        pb.setString("Item A", forType: .string)
        monitor.checkPasteboard()
        assert(monitor.items.count == 1, "Expected 1 item recorded")

        // Calling checkPasteboard() again with same changeCount should immediately return
        let initialCount = monitor.items.count
        monitor.checkPasteboard()
        assert(monitor.items.count == initialCount, "Item count should not change when changeCount is identical")
        print("✓ Test 1 Passed: ChangeCount guard exits immediately (zero CPU overhead)")
    }

    // MARK: - Test 2: Password Manager Suppression

    @MainActor
    static func testPasswordManagerSuppression() {
        let pb = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 50, autoStart: false)

        let concealedTypesToTest = [
            "org.nspasteboard.ConcealedType",
            "com.agilebits.onepassword",
            "com.agilebits.onepassword4",
            "org.nspasteboard.AutoGeneratedType",
            "org.nspasteboard.TransientType",
            "de.petermaurer.TransientPasteboardType",
            "com.typeit4me.clipping",
            "Pasteboard generator type",
            "com.custom.credential-item",
            "org.keepass.password-data"
        ]

        for typeName in concealedTypesToTest {
            pb.clearContents()
            pb.declareTypes([.string, NSPasteboard.PasteboardType(typeName)], owner: nil)
            pb.setString("SuperSecret_\(typeName)", forType: .string)
            monitor.checkPasteboard()

            assert(
                !monitor.items.contains(where: { $0.text.contains("SuperSecret") }),
                "Failed to suppress sensitive type: \(typeName)"
            )
        }

        print("✓ Test 2 Passed: Strict suppression of all concealed & credential pasteboard types")
    }

    // MARK: - Test 3: Text Extraction & Trimming

