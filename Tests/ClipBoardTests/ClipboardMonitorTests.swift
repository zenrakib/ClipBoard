    // MARK: - Test 10: Pin Local JSON Persistence

    @MainActor
    static func testPinPersistence() {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try? FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        let persistenceURL = tempDir.appendingPathComponent("pinned.json")

        let pb1 = NSPasteboard.withUniqueName()
        let monitor1 = ClipboardMonitor(
            pasteboard: pb1,
            pollInterval: 0.25,
            maxCapacity: 50,
            autoStart: false,
            enablePersistence: true,
            persistenceURL: persistenceURL
        )

        pb1.clearContents()
        pb1.setString("Favorite Note 1", forType: .string)
        monitor1.checkPasteboard()

        pb1.clearContents()
        pb1.setString("Regular Note", forType: .string)
        monitor1.checkPasteboard()

        pb1.clearContents()
        pb1.setString("Favorite Note 2", forType: .string)
        monitor1.checkPasteboard()

        assert(monitor1.items.count == 3)

        // Pin Note 1 and Note 2
        monitor1.togglePin(id: monitor1.items.first(where: { $0.text == "Favorite Note 1" })!.id)
        monitor1.togglePin(id: monitor1.items.first(where: { $0.text == "Favorite Note 2" })!.id)

        // Verify JSON file written to disk
        assert(FileManager.default.fileExists(atPath: persistenceURL.path), "pinned.json should exist on disk")

        // Instantiate second monitor reading from the same persistenceURL
        let pb2 = NSPasteboard.withUniqueName()
        let monitor2 = ClipboardMonitor(
            pasteboard: pb2,
            pollInterval: 0.25,
            maxCapacity: 50,
            autoStart: false,
            enablePersistence: true,
            persistenceURL: persistenceURL
        )

        assert(monitor2.items.count == 2, "Only pinned items should be loaded from persistence")
        assert(monitor2.items.allSatisfy { $0.isPinned }, "All loaded items should be marked isPinned")
        let loadedTexts = Set(monitor2.items.map(\.text))
        assert(loadedTexts == Set(["Favorite Note 1", "Favorite Note 2"]), "Persisted texts should match")

        // Cleanup
        try? FileManager.default.removeItem(at: tempDir)
        print("✓ Test 10 Passed: Pinned items saved to JSON and reloaded successfully")
    }

    // MARK: - Test 11: Clear Preserves Pinned Items

    @MainActor
    static func testClearPreservesPinnedItems() {
        let pb = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 50, autoStart: false)

        pb.clearContents()
        pb.setString("Temporary 1", forType: .string)
        monitor.checkPasteboard()

        pb.clearContents()
        pb.setString("Permanent Favorite", forType: .string)
        monitor.checkPasteboard()

        pb.clearContents()
        pb.setString("Temporary 2", forType: .string)
        monitor.checkPasteboard()

        assert(monitor.items.count == 3)

        // Pin the Permanent Favorite
        let favItem = monitor.items.first(where: { $0.text == "Permanent Favorite" })!
        monitor.togglePin(item: favItem)

        // Clear clipboard history
        monitor.clear()

        // Pinned item must remain, temporary items must be removed
        assert(monitor.items.count == 1, "Expected only 1 item remaining after clear")
        assert(monitor.items[0].text == "Permanent Favorite", "Pinned item must survive clear()")
        assert(monitor.items[0].isPinned == true, "Remaining item must still be pinned")

        print("✓ Test 11 Passed: clear() removes unpinned items while strictly preserving pinned items")
    }

    // MARK: - Test 12: Max Capacity Eviction Preserves Pinned Items

    @MainActor
    static func testCapacityEvictionPreservesPinnedItems() {
        let pb = NSPasteboard.withUniqueName()
        // Small capacity of 3
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 3, autoStart: false)

        pb.clearContents()
        pb.setString("Item 1 (Pinned)", forType: .string)
        monitor.checkPasteboard()
        monitor.togglePin(item: monitor.items[0])

        pb.clearContents()
        pb.setString("Item 2 (Unpinned)", forType: .string)
        monitor.checkPasteboard()

        pb.clearContents()
        pb.setString("Item 3 (Unpinned)", forType: .string)
        monitor.checkPasteboard()

        assert(monitor.items.count == 3)

        // Now push a 4th item. Capacity is 3. Item 1 is the oldest, but it is PINNED!
        // Therefore Item 2 (oldest unpinned) must be evicted instead of Item 1.
        pb.clearContents()
        pb.setString("Item 4 (Unpinned)", forType: .string)
        monitor.checkPasteboard()

        assert(monitor.items.count == 3, "Count should remain capped at maxCapacity (3)")
        assert(monitor.items.contains(where: { $0.text == "Item 1 (Pinned)" && $0.isPinned }), "Pinned item 1 must NEVER be evicted")
        assert(monitor.items[0].text == "Item 4 (Unpinned)", "Item 4 should be at top")
        assert(monitor.items.contains(where: { $0.text == "Item 3 (Unpinned)" }), "Item 3 should remain")
        assert(!monitor.items.contains(where: { $0.text == "Item 2 (Unpinned)" }), "Item 2 (oldest unpinned) should have been evicted")

        print("✓ Test 12 Passed: Capacity overflow skips pinned items and evicts oldest unpinned item")
    }

