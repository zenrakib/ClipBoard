    }

    // MARK: - Test 6: Copy To Pasteboard Without Recursion

    @MainActor
    static func testCopyToPasteboardWithoutRecursion() {
        let pb = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 50, autoStart: false)

        pb.clearContents()
        pb.setString("Entry 1", forType: .string)
        monitor.checkPasteboard()

        pb.clearContents()
        pb.setString("Entry 2", forType: .string)
        monitor.checkPasteboard()

        let item1 = monitor.items[1]
