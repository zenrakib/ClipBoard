    // MARK: - Test 8: Image / Screenshot Capture & Deduplication

    @MainActor
    static func testImageCaptureAndDeduplication() {
        let pb = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pb, pollInterval: 0.25, maxCapacity: 50, autoStart: false)

        // 1. Simulate a screenshot / copied PNG image
        let img = NSImage(size: NSSize(width: 400, height: 300))
        img.lockFocus()
        NSColor.cyan.drawSwatch(in: NSRect(x: 0, y: 0, width: 400, height: 300))
        img.unlockFocus()

        guard let tiff = img.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else {
            fatalError("Failed to generate test PNG")
        }

        pb.clearContents()
        pb.setData(png, forType: .png)
        pb.setData(tiff, forType: .tiff)
        monitor.checkPasteboard()

        assert(monitor.items.count == 1, "Expected 1 image item")
        assert(monitor.items[0].isImage == true, "Item should be marked as an image")
        assert(monitor.items[0].imageData == png, "Raw image data should match")
        assert(monitor.items[0].thumbnailData != nil, "Thumbnail data should be generated")
        let expectedDims = CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        assert(monitor.items[0].imageDimensions == expectedDims, "Dimensions should match extracted image pixels")

        // 2. Deduplicate image: push a text item, then re-copy the same image
        pb.clearContents()
        pb.setString("Interleaved Text", forType: .string)
        monitor.checkPasteboard()
        assert(monitor.items.count == 2)
        assert(monitor.items[0].text == "Interleaved Text")
        assert(monitor.items[1].isImage == true)

        // Re-copy the same image -> should bump to index 0 without duplicates
        pb.clearContents()
        pb.setData(png, forType: .png)
        monitor.checkPasteboard()
        assert(monitor.items.count == 2, "Stack should remain 2 items after image deduplication")
        assert(monitor.items[0].isImage == true, "Image should be promoted to index 0")
        assert(monitor.items[1].text == "Interleaved Text", "Text should be at index 1")

        // 3. Test copyToPasteboard for image without recursion
        let imageItem = monitor.items[0]
        monitor.copyToPasteboard(imageItem)
        assert(pb.data(forType: .png) == png, "Pasteboard should contain the image PNG")

        // Should not duplicate on checkPasteboard
        monitor.checkPasteboard()
        assert(monitor.items.count == 2, "checkPasteboard should not duplicate after copyToPasteboard")

        print("✓ Test 8 Passed: Image / screenshot capture, downscaled thumbnail, deduplication & copy")
    }

