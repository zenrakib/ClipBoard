        // checkPasteboard should recognize lastChangeCount is synchronized and not duplicate
        monitor.checkPasteboard()
        assert(monitor.items.count == 2)
        assert(monitor.items[0].text == "Entry 1")
        assert(monitor.items[1].text == "Entry 2")

        print("✓ Test 6 Passed: Copying back to pasteboard syncs changeCount without recursion")
    }

