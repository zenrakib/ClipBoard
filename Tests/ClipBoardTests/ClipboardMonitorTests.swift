        assert(monitor.items[0].text == "Important Snippet", "Important Snippet should be bumped to top")
        assert(monitor.items[0].isPinned == true, "Important Snippet must remain PINNED after deduplication")

        print("✓ Test 13 Passed: Deduplication preserves isPinned status")
    }

    // MARK: - Test 14: Drag & Drop Persistent Image Export & Multi-Flavor Writer

    @MainActor
    static func testDragAndDropImageAssetExportAndWriter() {
        let tempDir = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try? FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)

        let fakePNG = Data([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x01, 0x02, 0x03])
        let imageItem = ClipboardItem(
            imageData: fakePNG,
            thumbnailData: fakePNG,
            dimensions: CGSize(width: 100, height: 100)
        )

        // Export PNG asset to disk
        guard let exportedURL = ClipboardDragHelper.exportImageFile(for: imageItem, directory: tempDir) else {
            fatalError("Expected image asset to be exported")
        }
        assert(FileManager.default.fileExists(atPath: exportedURL.path), "Exported PNG file should exist on disk")
        assert((try? Data(contentsOf: exportedURL)) == fakePNG, "Exported file contents should match original PNG data")
        assert(exportedURL.pathExtension == "png", "Exported file should have .png extension")

        // Write to drag pasteboard using makePasteboardWriter
        let pb = NSPasteboard.withUniqueName()
        pb.clearContents()
        let writer = ClipboardDragHelper.makePasteboardWriter(for: imageItem, assetsDirectory: tempDir)
        let success = pb.writeObjects([writer])
        assert(success, "Should successfully write drag payload to pasteboard")

        // Verify both NSURL (for Premiere Pro / After Effects / Finder) and .png (for browsers / Figma) are present
        let readURLs = pb.readObjects(forClasses: [NSURL.self], options: nil) as? [URL]
        assert(readURLs?.first?.path == exportedURL.path, "Pasteboard should provide the exported file URL")
        assert(pb.data(forType: .png) == fakePNG, "Pasteboard should provide raw PNG data")

        let filenames = pb.propertyList(forType: NSPasteboard.PasteboardType("NSFilenamesPboardType")) as? [String]
        assert(filenames?.first == exportedURL.path, "NSFilenamesPboardType should contain file path for Adobe NLEs")

        try? FileManager.default.removeItem(at: tempDir)
        print("✓ Test 14 Passed: Image Drag & Drop exports persistent PNG and provides FileURL + NSFilenamesPboardType + PNG")
    }

